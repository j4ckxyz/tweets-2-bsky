export function writeCaddyfile(settings: PdsSettings, contactEmail?: string): string {
  fs.mkdirSync(PDS_DATA_DIR, { recursive: true });
  const caddyfile = path.join(PDS_DATA_DIR, 'Caddyfile');
  const emailLine = contactEmail ? `\temail ${contactEmail}\n` : '';
  fs.writeFileSync(
    caddyfile,
    `{\n${emailLine}\ton_demand_tls {\n\t\task http://localhost:${settings.port}/tls-check\n\t}\n}\n\n` +
      `*.${settings.hostname}, ${settings.hostname} {\n\ttls {\n\t\ton_demand\n\t}\n\treverse_proxy http://localhost:${settings.port}\n}\n`,
  );
  return caddyfile;
}
