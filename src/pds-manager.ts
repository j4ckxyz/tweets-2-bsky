export async function generateMissingPdsSecrets(envFile = ENV_FILE): Promise<{
  secrets: PdsSecrets;
  generated: PdsSecretKey[];
}> {
  const generated: PdsSecretKey[] = [];
  const secrets = {} as PdsSecrets;

  // Keys already present in the .env text (even with an empty value) must be
  // rewritten in place rather than appended, or the file accumulates duplicate
  // assignments and the last one silently wins.
  const existingEnvText = fs.existsSync(envFile) ? fs.readFileSync(envFile, 'utf8') : '';
  const keyIsDeclaredInFile = (key: PdsSecretKey) =>
    new RegExp(`^[ \\t]*(?:export[ \\t]+)?${key}[ \\t]*=`, 'm').test(existingEnvText);
  const rewrittenInPlace: PdsSecretKey[] = [];

  for (const key of PDS_SECRET_KEYS) {
    const existing = process.env[key]?.trim();
    if (existing) {
      secrets[key] = existing;
      continue;
    }

    let value: string;
    if (key === 'PDS_PLC_ROTATION_KEY_K256_PRIVATE_KEY_HEX') {
      const keypair = await Secp256k1Keypair.create({ exportable: true });
      value = Buffer.from(await keypair.export()).toString('hex');
    } else {
      value = randomBytes(24).toString('hex');
    }
    secrets[key] = value;
    process.env[key] = value;
    generated.push(key);
    if (keyIsDeclaredInFile(key)) {
      rewrittenInPlace.push(key);
    }
  }

  if (generated.length > 0) {
    let text = existingEnvText;
    for (const key of rewrittenInPlace) {
      text = text.replace(new RegExp(`^[ \\t]*(?:export[ \\t]+)?${key}[ \\t]*=.*$`, 'm'), `${key}=${secrets[key]}`);
    }
    const appended = generated.filter((key) => !rewrittenInPlace.includes(key));
    if (appended.length > 0) {
      const header = '\n# Built-in PDS secrets (generated by setup-pds; do not share)\n';
      const lines = appended.map((key) => `${key}=${secrets[key]}`);
      text = `${text}${header}${lines.join('\n')}\n`;
    }
    fs.writeFileSync(envFile, text);
  }

  return { secrets, generated };
}

export function getPdsSecrets(): PdsSecrets | null {
  const secrets = {} as PdsSecrets;
  for (const key of PDS_SECRET_KEYS) {
    const value = process.env[key]?.trim();
    if (!value) return null;
    secrets[key] = value;
  }
  return secrets;
}

