// @atproto/pds enforces these on the label in front of the service domain
// (ensureHandleServiceConstraints). Twitter caps usernames at 15 characters so
// the upper bound is unreachable in practice, but legacy 1-2 character handles
// do exist and would otherwise fail deep inside createAccount.
const PDS_LABEL_MIN_LENGTH = 3;
const PDS_LABEL_MAX_LENGTH = 18;

// Twitter usernames allow [A-Za-z0-9_], DNS labels do not allow "_". Handles
// like "some_user" become "some-user.example.com".
export function twitterHandleToPdsLabel(twitterUsername: string): string {
  const label = twitterUsername
    .trim()
    .replace(/^@/, '')
    .toLowerCase()
    .replace(/_/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/^-+|-+$/g, '');
  if (!label) {
    throw new Error(`Cannot derive a valid handle from Twitter username "${twitterUsername}"`);
  }
  if (label.length < PDS_LABEL_MIN_LENGTH) {
    throw new Error(
      `Twitter username "${twitterUsername}" maps to the handle label "${label}", which is shorter than the ${PDS_LABEL_MIN_LENGTH}-character minimum the AT Protocol enforces. Mirror this account to a manually created Bluesky account instead.`,
    );
  }
  if (label.length > PDS_LABEL_MAX_LENGTH) {
    throw new Error(
      `Twitter username "${twitterUsername}" maps to the handle label "${label}", which exceeds the ${PDS_LABEL_MAX_LENGTH}-character maximum the AT Protocol enforces.`,
    );
  }
  return label;
}

interface XrpcErrorBody {
  error?: string;
  message?: string;
}

async function xrpc<T>(
  localUrl: string,
  method: 'GET' | 'POST',
  nsid: string,
  options: { body?: unknown; adminPassword?: string; params?: Record<string, string> } = {},
): Promise<T> {
  const query = options.params ? `?${new URLSearchParams(options.params)}` : '';
  const headers: Record<string, string> = { 'Content-Type': 'application/json' };
  if (options.adminPassword) {
    headers.Authorization = `Basic ${Buffer.from(`admin:${options.adminPassword}`).toString('base64')}`;
  }
  const res = await fetch(`${localUrl}/xrpc/${nsid}${query}`, {
    method,
    headers,
    body: options.body === undefined ? undefined : JSON.stringify(options.body),
  });
  const data = (await res.json().catch(() => ({}))) as T & XrpcErrorBody;
  if (!res.ok) {
    const err = new Error(`${nsid} failed: ${data.message || data.error || res.status}`);
    (err as Error & { xrpcError?: string }).xrpcError = data.error;
    throw err;
  }
  return data;
}

interface SqliteDbLike {
  prepare: (sql: string) => { run: (...params: unknown[]) => unknown; get: (...params: unknown[]) => unknown };
  exec: (sql: string) => unknown;
  close: () => void;
}

// The PDS child process holds this database open in WAL mode and opens it with
// better-sqlite3's `timeout: 0`, handling contention with its own retry loop.
// Neither bun:sqlite nor better-sqlite3 sets a busy timeout by default, so
// without this an UPDATE landing during a PDS write fails immediately with
// SQLITE_BUSY.
const SQLITE_BUSY_TIMEOUT_MS = 5_000;

// Same runtime split as src/db.ts: bun:sqlite under bun (better-sqlite3's
// native module does not load there), better-sqlite3 under node.
export async function openSqliteDb(dbPath: string): Promise<SqliteDbLike> {
  let db: SqliteDbLike;
  if (typeof process.versions.bun === 'string') {
    const bunSqliteSpecifier = 'bun:sqlite';
    const sqliteModule = (await import(bunSqliteSpecifier)) as {
      Database: new (filename: string) => SqliteDbLike;
    };
    db = new sqliteModule.Database(dbPath);
  } else {
    const betterSqliteModule = await import('better-sqlite3');
    db = new betterSqliteModule.default(dbPath) as unknown as SqliteDbLike;
  }
  db.exec(`PRAGMA busy_timeout = ${SQLITE_BUSY_TIMEOUT_MS}`);
  return db;
}

// The account is created with a phony local email and then marked verified by
// writing emailConfirmedAt directly into the PDS account database — no real
// mailbox or SMTP setup is needed.
export async function markEmailConfirmed(did: string): Promise<void> {
  const accountDb = path.join(PDS_DATA_DIR, 'account.sqlite');
  if (!fs.existsSync(accountDb)) {
    throw new Error(`PDS account database not found at ${accountDb}`);
  }
  const backdated = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString();

  // busy_timeout covers the common case; the retry covers a write that spans
  // longer than the timeout (the PDS batches repo writes under load).
  const maxAttempts = 3;
  for (let attempt = 1; ; attempt += 1) {
    const db = await openSqliteDb(accountDb);
    try {
      db.prepare('UPDATE account SET emailConfirmedAt = ? WHERE did = ? AND emailConfirmedAt IS NULL').run(
        backdated,
        did,
      );
      return;
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      const isBusy = /SQLITE_BUSY|database is locked/i.test(message);
      if (!isBusy || attempt >= maxAttempts) {
        throw error;
      }
      await new Promise((resolve) => setTimeout(resolve, 250 * attempt));
    } finally {
      db.close();
    }
  }
}

export async function provisionPdsAccount(
  settings: PdsSettings,
  twitterUsername: string,
  onProgress: ProvisionProgress = () => {},
): Promise<ProvisionResult> {
  const secrets = getPdsSecrets();
  if (!secrets) {
    throw new Error('PDS secrets missing from environment. Run `bun run cli -- setup-pds` first.');
  }
  const adminPassword = secrets.PDS_ADMIN_PASSWORD;
  const localUrl = `http://127.0.0.1:${settings.port}`;

  const label = twitterHandleToPdsLabel(twitterUsername);
  const handle = `${label}.${settings.hostname}`;
  // Phony address; never receives mail (verification is backdated in SQL).
  // The PDS validates email syntax including TLD, so ".test" hostnames fall back
  // to example.com.
  const emailDomain =
    settings.hostname.includes('.') && !isDevPdsHostname(settings.hostname) ? settings.hostname : 'example.com';
  const email = `${label}@${emailDomain}`;
  const password = randomBytes(18).toString('base64url');

  onProgress('Creating invite code');
  const invite = await xrpc<{ code: string }>(localUrl, 'POST', 'com.atproto.server.createInviteCode', {
    body: { useCount: 1 },
    adminPassword,
  });

  onProgress(`Creating account ${handle}`);
  try {
    const created = await xrpc<{ did: string }>(localUrl, 'POST', 'com.atproto.server.createAccount', {
      body: { email, handle, password, inviteCode: invite.code },
    });

    onProgress('Marking email as verified (backdated)');
    await markEmailConfirmed(created.did);

    return { twitterUsername, handle, did: created.did, password, existing: false };
  } catch (error) {
    const { xrpcError } = error as Error & { xrpcError?: string };
    const message = error instanceof Error ? error.message : '';
    const handleTaken =
      xrpcError === 'HandleNotAvailable' || xrpcError === 'AlreadyExists' || message.includes('Handle already taken');
    if (!handleTaken) {
      // The handle is free but the address is spoken for: an earlier account was
      // renamed away from this handle and still holds the derived email. Nothing
      // here can recover it automatically, so say what to do about it.
      if (message.includes('Email already taken')) {
        throw new Error(
          `The address ${email} is already registered on this PDS under a different handle (an account was probably renamed). Delete or re-point that account with the PDS admin API, then re-run this command.`,
        );
      }
      throw error;
    }

    // Account already exists (e.g. wizard re-run). Reset its password via the
    // admin API so we always end up with working credentials.
    onProgress(`Account ${handle} already exists — resetting password`);
    const resolved = await xrpc<{ did: string }>(localUrl, 'GET', 'com.atproto.identity.resolveHandle', {
      params: { handle },
    });
    await xrpc(localUrl, 'POST', 'com.atproto.admin.updateAccountPassword', {
      body: { did: resolved.did, password },
      adminPassword,
    });

    onProgress('Marking email as verified (backdated)');
    await markEmailConfirmed(resolved.did);

    return { twitterUsername, handle, did: resolved.did, password, existing: true };
  }
}

