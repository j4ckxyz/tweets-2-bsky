const isLocalHostname = (hostname: string) =>
  hostname === 'localhost' || hostname.endsWith('.localhost') || hostname.endsWith('.test');

function buildPdsEnv(settings: PdsSettings, secrets: PdsSecrets): Record<string, string> {
  fs.mkdirSync(PDS_DATA_DIR, { recursive: true });
  fs.mkdirSync(path.join(PDS_DATA_DIR, 'blocks'), { recursive: true });

  const env: Record<string, string> = {
    PDS_HOSTNAME: settings.hostname,
    PDS_PORT: String(settings.port),
    PDS_DATA_DIRECTORY: PDS_DATA_DIR,
    PDS_BLOBSTORE_DISK_LOCATION: path.join(PDS_DATA_DIR, 'blocks'),
    PDS_BLOB_UPLOAD_LIMIT: '52428800',
    PDS_DID_PLC_URL: 'https://plc.directory',
    PDS_BSKY_APP_VIEW_URL: 'https://api.bsky.app',
    PDS_BSKY_APP_VIEW_DID: 'did:web:api.bsky.app',
    PDS_REPORT_SERVICE_URL: 'https://mod.bsky.app',
    PDS_REPORT_SERVICE_DID: 'did:plc:ar7c4by46qjdydhdevvrndac',
    PDS_CRAWLERS: 'https://bsky.network',
    PDS_INVITE_REQUIRED: 'true',
    LOG_ENABLED: process.env.PDS_LOG_ENABLED ?? 'false',
    ...secrets,
  };

  if (isLocalHostname(settings.hostname)) {
    // Local/test mode: no public DNS or TLS available.
    env.PDS_DEV_MODE = 'true';
  }

  const smtpUrl = process.env.PDS_EMAIL_SMTP_URL?.trim();
  const fromAddress = process.env.PDS_EMAIL_FROM_ADDRESS?.trim();
  if (smtpUrl && fromAddress) {
    env.PDS_EMAIL_SMTP_URL = smtpUrl;
    env.PDS_EMAIL_FROM_ADDRESS = fromAddress;
  }

  return env;
}

// @atproto/pds depends on undici v8, which cannot load under bun — so the PDS
// runs as a Node child process while the rest of the app stays on bun.
function findNodeBinary(): string {
  const candidates = process.versions.bun ? ['node'] : [process.execPath, 'node'];
  for (const candidate of candidates) {
    try {
      const version = execFileSync(candidate, ['--version'], { encoding: 'utf8' }).trim();
      const major = Number.parseInt(version.replace(/^v/, '').split('.')[0] ?? '0', 10);
      if (major >= 22) return candidate;
      console.warn(`Found ${candidate} ${version}, but the built-in PDS needs Node 22+.`);
    } catch {
      // try next candidate
    }
  }
  throw new Error('Node.js 22+ is required to run the built-in PDS. Install it from https://nodejs.org.');
}

// Installs the PDS service dependencies on first use, with npm so native
// modules are built for the Node child process (not bun's ABI).
export function ensurePdsServiceDeps(): void {
  if (fs.existsSync(path.join(PDS_SERVICE_DIR, 'node_modules', '@atproto', 'pds'))) {
    return;
  }
  console.log('📦 Installing built-in PDS dependencies (first run only)...');
  execFileSync('npm', ['install', '--no-audit', '--no-fund'], {
    cwd: PDS_SERVICE_DIR,
    stdio: 'inherit',
  });
}

export async function startPds(settings: PdsSettings): Promise<PdsHandle> {
  const secrets = getPdsSecrets();
  if (!secrets) {
    throw new Error('PDS secrets missing from environment. Run `bun run cli -- setup-pds` first.');
  }
  if (!fs.existsSync(PDS_SERVICE_ENTRY)) {
    throw new Error(`PDS service entry not found at ${PDS_SERVICE_ENTRY}`);
  }
  ensurePdsServiceDeps();

  const localUrlPrecheck = `http://127.0.0.1:${settings.port}`;
  if (await isPdsHealthy(localUrlPrecheck)) {
    throw new Error(`Port ${settings.port} is already serving a PDS. Use the running instance or stop it first.`);
  }

  const nodeBinary = findNodeBinary();
  const env = buildPdsEnv(settings, secrets);
  const logPath = path.join(PDS_DATA_DIR, 'pds.log');
  const logFd = fs.openSync(logPath, 'a');

  const child: ChildProcess = spawn(nodeBinary, [PDS_SERVICE_ENTRY], {
    cwd: PDS_SERVICE_DIR,
    env: { ...process.env, ...env },
    stdio: ['ignore', logFd, logFd],
  });
  fs.closeSync(logFd);

  // The PDS must never outlive the parent — an orphan would keep the port
  // busy and serve stale config to the next run.
  const killChildOnExit = () => {
    child.kill('SIGTERM');
  };
  process.once('exit', killChildOnExit);

  let exited = false;
  child.on('exit', (code, signal) => {
    exited = true;
    process.removeListener('exit', killChildOnExit);
    if (code !== 0 && signal !== 'SIGTERM' && signal !== 'SIGINT') {
      console.error(`⚠️ Built-in PDS exited unexpectedly (code ${code}, signal ${signal}). See ${logPath}`);
    }
  });

  const localUrl = `http://127.0.0.1:${settings.port}`;
  try {
    await waitForPdsHealthy(localUrl, 30_000, () => exited);
  } catch (error) {
    child.kill('SIGTERM');
    throw new Error(`${(error as Error).message}. Check the PDS log: ${logPath}`);
  }

  return {
    port: settings.port,
    hostname: settings.hostname,
    localUrl,
    stop: async () => {
      if (exited) return;
      await new Promise<void>((resolve) => {
        const timeout = setTimeout(() => {
          child.kill('SIGKILL');
          resolve();
        }, 5_000);
        child.once('exit', () => {
          clearTimeout(timeout);
          resolve();
        });
        child.kill('SIGTERM');
      });
    },
  };
}

export async function isPdsHealthy(localUrl: string): Promise<boolean> {
  try {
    const res = await fetch(`${localUrl}/xrpc/_health`, { signal: AbortSignal.timeout(2_000) });
    return res.ok;
  } catch {
    return false;
  }
}

async function waitForPdsHealthy(localUrl: string, timeoutMs = 15_000, hasExited?: () => boolean): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (hasExited?.()) {
      throw new Error('PDS process exited before becoming healthy');
    }
    if (await isPdsHealthy(localUrl)) return;
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`PDS did not become healthy at ${localUrl} within ${timeoutMs}ms`);
}

