export async function generateMissingPdsSecrets(envFile = ENV_FILE): Promise<{
  secrets: PdsSecrets;
  generated: PdsSecretKey[];
}> {
  const generated: PdsSecretKey[] = [];
  const secrets = {} as PdsSecrets;

  for (const key of PDS_SECRET_KEYS) {
    const existing = process.env[key]?.trim();
    if (existing) {
      secrets[key] = existing;
      continue;
    }

    let value: string;
    if (key === 'PDS_PLC_ROTATION_KEY_K256_PRIVATE_KEY_HEX') {
      const keypair = await Secp256k1Keypair.create({ exportable: true });
      value = Buffer.from(await keypair.export()).toString('hex');
    } else {
      value = randomBytes(24).toString('hex');
    }
    secrets[key] = value;
    process.env[key] = value;
    generated.push(key);
  }

  if (generated.length > 0) {
    const lines = generated.map((key) => `${key}=${secrets[key]}`);
    const header = '\n# Built-in PDS secrets (generated by setup-pds; do not share)\n';
    fs.appendFileSync(envFile, `${header}${lines.join('\n')}\n`);
  }

  return { secrets, generated };
}

export function getPdsSecrets(): PdsSecrets | null {
  const secrets = {} as PdsSecrets;
  for (const key of PDS_SECRET_KEYS) {
    const value = process.env[key]?.trim();
    if (!value) return null;
    secrets[key] = value;
  }
  return secrets;
}

