// Mirrors DISALLOWED_TLDS in @atproto/syntax. Handles under these TLDs are
// rejected by the PDS at account creation ("Handle TLD is invalid or
// disallowed"), so a PDS hostname ending in one can never provision an account.
// ".test" is deliberately absent: atproto allows it for local development.
const DISALLOWED_HANDLE_TLDS = [
  '.local',
  '.arpa',
  '.invalid',
  '.localhost',
  '.internal',
  '.example',
  '.alt',
  '.onion',
] as const;

// A ".test" hostname is the only supported way to run the PDS without public
// DNS or TLS. Plain "localhost" does NOT work: @atproto/pds forces
// serviceHandleDomains to [".test"] for that hostname, and ".localhost" is a
// disallowed handle TLD besides.
export const isDevPdsHostname = (hostname: string) => hostname === 'test' || hostname.endsWith('.test');

// Rejects hostnames that cannot host atproto handles, with the reason, before
// the wizard spends time generating secrets and booting a server.
export function validatePdsHostname(hostname: string): { ok: true } | { ok: false; reason: string } {
  const normalized = hostname.trim().toLowerCase();
  if (!normalized) {
    return { ok: false, reason: 'Hostname is required.' };
  }
  if (normalized === 'localhost') {
    return {
      ok: false,
      reason:
        'The hostname "localhost" cannot host atproto handles: @atproto/pds restricts it to ".test" handles, and ".localhost" is a disallowed handle TLD. Use a ".test" hostname for local runs (for example "t2b.test") or a real domain you control.',
    };
  }
  const badTld = DISALLOWED_HANDLE_TLDS.find((tld) => normalized.endsWith(tld));
  if (badTld) {
    return {
      ok: false,
      reason: `Handles under "${badTld}" are rejected by the AT Protocol (reserved TLD). Use a ".test" hostname for local runs or a real domain you control.`,
    };
  }
  if (!normalized.includes('.')) {
    return {
      ok: false,
      reason: `"${normalized}" has no TLD, so handles like "someone.${normalized}" will never resolve. Use a ".test" hostname for local runs or a real domain you control.`,
    };
  }
  if (!/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/.test(normalized)) {
    return { ok: false, reason: `"${normalized}" is not a valid domain name.` };
  }
  return { ok: true };
}

export function assertValidPdsHostname(hostname: string): void {
  const result = validatePdsHostname(hostname);
  if (!result.ok) {
    throw new Error(result.reason);
  }
}

function buildPdsEnv(settings: PdsSettings, secrets: PdsSecrets): Record<string, string> {
  fs.mkdirSync(PDS_DATA_DIR, { recursive: true });
  fs.mkdirSync(path.join(PDS_DATA_DIR, 'blocks'), { recursive: true });

  const env: Record<string, string> = {
    PDS_HOSTNAME: settings.hostname,
    PDS_PORT: String(settings.port),
    PDS_DATA_DIRECTORY: PDS_DATA_DIR,
    PDS_BLOBSTORE_DISK_LOCATION: path.join(PDS_DATA_DIR, 'blocks'),
    PDS_BLOB_UPLOAD_LIMIT: '52428800',
    PDS_DID_PLC_URL: 'https://plc.directory',
    PDS_BSKY_APP_VIEW_URL: 'https://api.bsky.app',
    PDS_BSKY_APP_VIEW_DID: 'did:web:api.bsky.app',
    PDS_REPORT_SERVICE_URL: 'https://mod.bsky.app',
    PDS_REPORT_SERVICE_DID: 'did:plc:ar7c4by46qjdydhdevvrndac',
    PDS_CRAWLERS: 'https://bsky.network',
    PDS_INVITE_REQUIRED: 'true',
    LOG_ENABLED: process.env.PDS_LOG_ENABLED ?? 'false',
    // @atproto/pds calls app.listen(port) with no host, which binds 0.0.0.0 and
    // would expose the whole PDS over cleartext HTTP on a public IP, bypassing
    // the TLS proxy. pds-service/index.mjs binds this host instead. Override to
    // 0.0.0.0 only when the reverse proxy cannot reach loopback (e.g. Caddy in a
    // bridge-network container) — and firewall the port if you do.
    PDS_BIND_HOST: process.env.PDS_BIND_HOST?.trim() || '127.0.0.1',
    ...secrets,
  };

  if (isDevPdsHostname(settings.hostname)) {
    // Local/test mode: no public DNS or TLS available.
    env.PDS_DEV_MODE = 'true';
  }

  const smtpUrl = process.env.PDS_EMAIL_SMTP_URL?.trim();
  const fromAddress = process.env.PDS_EMAIL_FROM_ADDRESS?.trim();
  if (smtpUrl && fromAddress) {
    env.PDS_EMAIL_SMTP_URL = smtpUrl;
    env.PDS_EMAIL_FROM_ADDRESS = fromAddress;
  }

  return env;
}

// @atproto/pds depends on undici v8, which cannot load under bun — so the PDS
// runs as a Node child process while the rest of the app stays on bun.
function findNodeBinary(): string {
  const candidates = process.versions.bun ? ['node'] : [process.execPath, 'node'];
  for (const candidate of candidates) {
    try {
      const version = execFileSync(candidate, ['--version'], { encoding: 'utf8' }).trim();
      const major = Number.parseInt(version.replace(/^v/, '').split('.')[0] ?? '0', 10);
      if (major >= 22) return candidate;
      console.warn(`Found ${candidate} ${version}, but the built-in PDS needs Node 22+.`);
    } catch {
      // try next candidate
    }
  }
  throw new Error('Node.js 22+ is required to run the built-in PDS. Install it from https://nodejs.org.');
}

// Installs the PDS service dependencies on first use, with npm so native
// modules are built for the Node child process (not bun's ABI). Docker images
// pre-install these at build time, so this is a no-op there.
export function ensurePdsServiceDeps(): void {
  if (fs.existsSync(path.join(PDS_SERVICE_DIR, 'node_modules', '@atproto', 'pds'))) {
    return;
  }
  console.log('📦 Installing built-in PDS dependencies (first run only)...');
  try {
    execFileSync('npm', ['install', '--no-audit', '--no-fund'], {
      cwd: PDS_SERVICE_DIR,
      stdio: 'inherit',
    });
  } catch (error) {
    const code = (error as { code?: string }).code;
    if (code === 'ENOENT') {
      throw new Error(
        'npm was not found on PATH, so the built-in PDS dependencies cannot be installed. The PDS runs under Node.js (not bun) and needs its own node_modules — install Node.js 22+ (which ships npm) and re-run.',
      );
    }
    throw new Error(
      `Installing the built-in PDS dependencies failed (npm install in ${PDS_SERVICE_DIR}). Fix the npm error above, or run "npm install" in that directory manually, then retry.`,
    );
  }
}

export interface StartPdsOptions {
  // Restart the PDS if it dies unexpectedly. Long-running processes (`bun start`)
  // want this; short-lived CLI commands do not.
  superviseOnCrash?: boolean;
}

const PDS_RESTART_MIN_DELAY_MS = 1_000;
const PDS_RESTART_MAX_DELAY_MS = 60_000;
// Once the PDS has stayed up this long, treat the next crash as a fresh
// incident rather than continuing to back off.
const PDS_RESTART_BACKOFF_RESET_MS = 60_000;

export async function startPds(settings: PdsSettings, options: StartPdsOptions = {}): Promise<PdsHandle> {
  const secrets = getPdsSecrets();
  if (!secrets) {
    throw new Error('PDS secrets missing from environment. Run `bun run cli -- setup-pds` first.');
  }
  if (!fs.existsSync(PDS_SERVICE_ENTRY)) {
    throw new Error(
      `The built-in PDS runtime is missing from this install (expected ${PDS_SERVICE_ENTRY}). Reinstall from source, or run ./update.sh to pull it in.`,
    );
  }
  assertValidPdsHostname(settings.hostname);
  ensurePdsServiceDeps();

  const localUrl = `http://127.0.0.1:${settings.port}`;
  if (await isPdsHealthy(localUrl)) {
    throw new Error(`Port ${settings.port} is already serving a PDS. Use the running instance or stop it first.`);
  }

  const nodeBinary = findNodeBinary();
  const env = buildPdsEnv(settings, secrets);
  const logPath = path.join(PDS_DATA_DIR, 'pds.log');

  let child: ChildProcess | null = null;
  let stopping = false;
  let restartDelayMs = PDS_RESTART_MIN_DELAY_MS;
  let restartTimer: NodeJS.Timeout | null = null;

  // The PDS must never outlive the parent — an orphan would keep the port
  // busy and serve stale config to the next run.
  const killChildOnExit = () => {
    child?.kill('SIGTERM');
  };
  process.once('exit', killChildOnExit);

  const spawnChild = (): ChildProcess => {
    const logFd = fs.openSync(logPath, 'a');
    const spawned = spawn(nodeBinary, [PDS_SERVICE_ENTRY], {
      cwd: PDS_SERVICE_DIR,
      env: { ...process.env, ...env },
      stdio: ['ignore', logFd, logFd],
    });
    fs.closeSync(logFd);
    const startedAt = Date.now();

    spawned.on('exit', (code, signal) => {
      if (spawned !== child) {
        // Superseded by a restart; its exit is not interesting.
        return;
      }
      child = null;
      const deliberate = stopping || signal === 'SIGTERM' || signal === 'SIGINT';
      if (deliberate) {
        process.removeListener('exit', killChildOnExit);
        return;
      }

      console.error(`⚠️ Built-in PDS exited unexpectedly (code ${code}, signal ${signal}). See ${logPath}`);
      if (!options.superviseOnCrash) {
        console.error('⚠️ Mirroring will fail until the PDS is running again. Restart the app to bring it back.');
        process.removeListener('exit', killChildOnExit);
        return;
      }

      if (Date.now() - startedAt >= PDS_RESTART_BACKOFF_RESET_MS) {
        restartDelayMs = PDS_RESTART_MIN_DELAY_MS;
      }
      const delay = restartDelayMs;
      restartDelayMs = Math.min(restartDelayMs * 2, PDS_RESTART_MAX_DELAY_MS);
      console.error(`🛰️ Restarting the built-in PDS in ${Math.round(delay / 1000)}s...`);
      restartTimer = setTimeout(() => {
        restartTimer = null;
        if (stopping) return;
        child = spawnChild();
        void waitForPdsHealthy(localUrl, 30_000, () => child === null)
          .then(() => console.log('🛰️ Built-in PDS is healthy again.'))
          .catch((error) => console.error(`⚠️ Built-in PDS did not come back: ${(error as Error).message}`));
      }, delay);
    });

    return spawned;
  };

  child = spawnChild();

  try {
    await waitForPdsHealthy(localUrl, 30_000, () => child === null);
  } catch (error) {
    stopping = true;
    child?.kill('SIGTERM');
    process.removeListener('exit', killChildOnExit);
    throw new Error(`${(error as Error).message}. Check the PDS log: ${logPath}`);
  }

  return {
    port: settings.port,
    hostname: settings.hostname,
    localUrl,
    stop: async () => {
      stopping = true;
      if (restartTimer) {
        clearTimeout(restartTimer);
        restartTimer = null;
      }
      const current = child;
      process.removeListener('exit', killChildOnExit);
      if (!current) return;
      await new Promise<void>((resolve) => {
        const timeout = setTimeout(() => {
          current.kill('SIGKILL');
          resolve();
        }, 5_000);
        current.once('exit', () => {
          clearTimeout(timeout);
          resolve();
        });
        current.kill('SIGTERM');
      });
    },
  };
}

export async function isPdsHealthy(localUrl: string): Promise<boolean> {
  try {
    const res = await fetch(`${localUrl}/xrpc/_health`, { signal: AbortSignal.timeout(2_000) });
    return res.ok;
  } catch {
    return false;
  }
}

async function waitForPdsHealthy(localUrl: string, timeoutMs = 15_000, hasExited?: () => boolean): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (hasExited?.()) {
      throw new Error('PDS process exited before becoming healthy');
    }
    if (await isPdsHealthy(localUrl)) return;
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`PDS did not become healthy at ${localUrl} within ${timeoutMs}ms`);
}

