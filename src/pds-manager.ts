const PDS_SECRET_KEYS = ['PDS_JWT_SECRET', 'PDS_ADMIN_PASSWORD', 'PDS_PLC_ROTATION_KEY_K256_PRIVATE_KEY_HEX'] as const;
type PdsSecretKey = (typeof PDS_SECRET_KEYS)[number];
export type PdsSecrets = Record<PdsSecretKey, string>;

export interface PdsHandle {
  port: number;
  hostname: string;
  localUrl: string;
  stop: () => Promise<void>;
}

export interface ProvisionResult {
  twitterUsername: string;
  handle: string;
  did: string;
  password: string;
  existing: boolean;
}

export type ProvisionProgress = (step: string) => void;

